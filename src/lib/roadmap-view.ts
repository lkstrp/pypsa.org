// Render `code` spans in descriptions as <code>. Content is hardcoded
// developer strings (no user input), so escaping + {@html} is safe.
export function formatDescription(text: string): string {
  const escaped = text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return escaped.replace(
    /`([^`]+)`/g,
    '<code class="rounded bg-muted px-1 py-0.5 text-[0.85em] font-mono">$1</code>'
  );
}

// Planned items (no date) keep their order; shipped items (dated) sort newest first.
export function splitRoadmap(items: RoadmapItem[]): {
  planned: RoadmapItem[];
  shipped: RoadmapItem[];
} {
  return {
    planned: items.filter((i) => !i.date),
    shipped: items.filter((i) => i.date).sort((a, b) => (b.date ?? "").localeCompare(a.date ?? "")),
  };
}
